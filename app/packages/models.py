import uuid
from datetime import datetime

from sqlalchemy import Column, DateTime, Float, Integer, String

from packages.db import Base


class User(Base):
    """
    SQLAlchemy ORM model for persisted user/auth data.

    Meta for this project:
    - only backend-owned data should live in Postgres
    - for this assignment, that mainly means users/auth fields
    - exchange state like orders, balances, fills, and orderbook depth
      belongs to the engine process in memory, not this ORM layer
    """

    __tablename__ = "users"

    # Primary keys should be stable, unique, and generated by the model layer.
    # We pass a callable here so a fresh UUID is generated for each new row.
    id = Column(String, primary_key=True, default=lambda: str(uuid.uuid4()))
    # Fields used to identify or search users should usually be indexed.
    # `nullable=False` means the column is required at the database level too,
    # not just in Pydantic request validation.
    username = Column(String, unique=True, index=True, nullable=False)

    # Never store plain passwords. This column stores the hashed password only.
    password = Column(String, nullable=False)

    # Example of another user-owned field that benefits from uniqueness.
    phone_number = Column(Integer, unique=True, index=True, nullable=True)


class AccountBalance(Base):
    __tablename__ = "account_balances"

    user_id = Column(String, primary_key=True)
    available = Column(Float, nullable=False, default=0)
    locked = Column(Float, nullable=False, default=0)
    updated_at = Column(DateTime, nullable=False, default=datetime.now(), onupdate=datetime.now())


class OrderProjection(Base):
    __tablename__ = "order_projections"

    order_id = Column(String, primary_key=True)
    user_id = Column(String, nullable=False)
    market = Column(String, nullable=False)
    status = Column(String, nullable=False)
    remaining_qty = Column(Float, nullable=False)
    updated_at = Column(DateTime, nullable=False, default=datetime.now(), onupdate=datetime.now())


class FillProjection(Base):
    __tablename__ = "fill_projections"

    fill_id = Column(String, primary_key=True)
    market = Column(String, nullable=False)
    maker_order_id = Column(String, nullable=False)
    taker_order_id = Column(String, nullable=False)
    maker_user_id = Column(String, nullable=False)
    taker_user_id = Column(String, nullable=False)
    price = Column(Float, nullable=False)
    qty = Column(Float, nullable=False)
    timestamp_ms = Column(Float, nullable=False)


class PositionProjection(Base):
    __tablename__ = "position_projections"

    user_id = Column(String, primary_key=True)
    market = Column(String, primary_key=True)
    qty = Column(Float, nullable=False)
    entry_price = Column(Float, nullable=False)
    margin = Column(Float, nullable=False)
    liquidation_price = Column(Float, nullable=False)
    realized_pnl = Column(Float, nullable=True)
    updated_at = Column(DateTime, nullable=False, default=datetime.now(), onupdate=datetime.now())
